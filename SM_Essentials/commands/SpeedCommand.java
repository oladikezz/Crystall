   private float mapWalkSpeed(int level) {
      float min = 0.2F;
      float max = 1.0F;
      if (level <= 1) {
         return min;
      }
      if (level >= 10) {
         return max;
      }
      float t = (level - 1) / 9.0F;
      return min + (max - min) * t;
   }

   private float mapFlySpeed(int level) {
      float min = 0.1F;
      float max = 1.0F;
      if (level <= 1) {
         return min;
      }
      if (level >= 10) {
         return max;
      }
      float t = (level - 1) / 9.0F;
      return min + (max - min) * t;
   }

   @Override
   public Collection<String> suggest(CommandSourceStack stack, String[] args) {
      if (args.length == 1) {
         return this.suggestLevels(args[0]);
      }
      if (args.length == 2 && stack.getSender().hasPermission("smess.speed.others")) {
         String input = args[1].toLowerCase();
         return this.plugin.getServer().getOnlinePlayers().stream()
            .map(Player::getName)
            .filter((name) -> name.toLowerCase().startsWith(input))
            .collect(Collectors.toList());
      }
      return new ArrayList<>();
   }

   private Collection<String> suggestLevels(String input) {
      String prefix = input == null ? "" : input;
      Collection<String> levels = new ArrayList<>();
      for (int i = 1; i <= 10; i++) {
         String value = Integer.toString(i);
         if (value.startsWith(prefix)) {
            levels.add(value);
         }
      }
      return levels;
   }

   private void highlightForAdmins(CommandSender sender, String[] args) {
      if (!this.module.isAdminHighlightEnabled()) {
         return;
      }
      String commandLine = "/" + getName();
      if (args.length > 0) {
         commandLine += " " + String.join(" ", args);
      }
      String message = this.module.formatAdminLog(sender.getName(), commandLine);
      for (Player player : this.plugin.getServer().getOnlinePlayers()) {
         if (player.isOp() || player.hasPermission(ADMIN_PERMISSION)) {
            if (!this.module.isAdminLogEnabled(player.getUniqueId())) {
               continue;
            }
            String taskName = "cmd-highlight-" + player.getUniqueId() + "-" + UUID.randomUUID();
            this.plugin.getSchedulerManager().runEntityTask(player, taskName, () -> {
               if (player.isOnline()) {
                  player.sendMessage(message);
               }
            });
         }
      }

      if (!(sender instanceof Player)) {
         sender.sendMessage(message);
      }
   }

   private void sendMessage(CommandSender sender, String message) {
      if (message == null || message.isEmpty()) {
         return;
      }
      if (sender instanceof Player player) {
         this.plugin.getSchedulerManager().runEntityTask(player, "speed-command-message", () -> {
            if (player.isOnline()) {
               player.sendMessage(message);
            }
         });
      } else {
         sender.sendMessage(message);
      }
   }
